/**
 * nspam — the reply-spam model, ported from Sidecar's nspam.js (MIT).
 *
 * WHAT IT IS. nspam (https://huggingface.co/barrydeen/nspam, MIT) scores a bundle of 1 to 10
 * replies from ONE author as human or reply-spam bot, from their words and their shape: links,
 * mentions, tags, emoji, capitals, and how alike the replies are to each other. It reads no
 * profile and no follow graph, which is what makes it a good second opinion beside the follow
 * list: the follow list knows who your circle is and nothing about a stranger; this knows
 * nothing about your circle, and something about the stranger.
 *
 * HOW IT RUNS. The model is 500 LightGBM trees, packed by Sidecar's scripts/build-nspam-model.py
 * into static/models/nspam.bin (format there). Scoring is a walk down each tree: no WebAssembly,
 * no ONNX, no network. Everything before the trees is a port of the training pipeline's features,
 * from the Go port in nspam-strfry, which is bit-exact against it; the reference cases the model
 * ships (src/test/fixtures/nspam) hold this file to it in nspam.test.ts. Go's regular
 * expressions read \s and \w as ASCII, so every pattern below spells its classes out rather
 * than trusting JavaScript's Unicode-aware ones.
 *
 * WHAT IT IS NOT. A verdict. The caller turns a score into a decision (see spamFilter.ts).
 */

