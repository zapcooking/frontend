export function casefold(s: string): string {
  let out = '';
  for (const c of s) {
    const folded = FOLD.get(c);
    out += folded ?? c.toLowerCase();
  }
  return out;
}

// PYTHON'S WHITESPACE AND WORD CHARACTERS, not JavaScript's and not Go's. The model was trained
// in Python, where \s and \w are Unicode-aware; JavaScript's \s adds U+FEFF and leaves out
// U+001C-001F and U+0085, and the Go port reads them as ASCII. One reference case caught it:
// "20<no-break space>000" is two tokens to Python and one to Go, and the score moved.
const WS =
  '\\t\\n\\v\\f\\r\\x1c-\\x1f \\x85\\xa0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000';
const W = '\\p{L}\\p{M}\\p{N}_';
const SPACE_RUN = new RegExp('[' + WS + ']+', 'gu');
const TRIM = new RegExp('^[' + WS + ']+|[' + WS + ']+$', 'gu');
const pyTrim = (s: string) => s.replace(TRIM, '');
const SPLIT = new RegExp('[' + WS + ']+', 'u');
const URL_FULL = new RegExp('https?://([^' + WS + '/]+)(/[^' + WS + ']*)?', 'giu');
const URL_HOST = new RegExp('https?://([^' + WS + '/]+)', 'giu');
const MENTION = /\b(?:nostr:)?(?:npub1|note1|nprofile1|nevent1|naddr1)[0-9a-z]+/gi;
const HASHTAG = new RegExp('#[' + W + ']+', 'gu');
const DIGIT = /\p{N}/gu;
const PUNCT = /\p{P}/gu;
const NONSPACE = new RegExp('[^' + WS + ']+', 'gu');
const LETTER = /\p{L}/u;
const UPPER = /\p{Lu}/u;
const EMOJI = /[\p{Emoji_Presentation}\p{Extended_Pictographic}]/u;
const WORD_TOKEN = new RegExp('[' + W + ']{2,}', 'gu');
const GROUP_TOKEN = new RegExp(
  '\\p{L}[' + W + ']*|\\p{N}+|https?://[^' + WS + ']+|[#@][' + W + ']+',
  'gu'
);
const count = (re: RegExp, s: string) => (s.match(re) || []).length;

function stripInvisible(s: string): string {
  let out = '';
  for (const c of s) if (!INVISIBLE.has(c)) out += c;
  return out;
}
function countInvisible(s: string): number {
  let n = 0;
  for (const c of s) if (INVISIBLE.has(c)) n++;
  return n;
}

// The two views of a note: the word view (normalized, no invisibles, links cut to their host,
// casefolded, one space between words) and the raw view (NFKC only) the character n-grams read.
function prepare(text: string) {
  const nfkc = String(text || '').normalize('NFKC');
  let s = stripInvisible(nfkc);
  s = s.replace(URL_FULL, (_, host: string) => 'http://' + host.toLowerCase());
  s = casefold(s).replace(SPACE_RUN, ' ');
  return { text: pyTrim(s), raw: nfkc };
}

// MurmurHash3 x86 32-bit, seed 0, over the UTF-8 bytes: scikit-learn's murmurhash3_32.
const utf8 = new TextEncoder();
function murmur3(str: string): number {
  const b = utf8.encode(str);
  const n = b.length;
  const blocks = n & ~3;
  let h = 0;
  for (let i = 0; i < blocks; i += 4) {
    let k = b[i] | (b[i + 1] << 8) | (b[i + 2] << 16) | (b[i + 3] << 24);
    k = Math.imul(k, 0xcc9e2d51);
    k = (k << 15) | (k >>> 17);
    k = Math.imul(k, 0x1b873593);
    h ^= k;
    h = (h << 13) | (h >>> 19);
    h = (Math.imul(h, 5) + 0xe6546b64) | 0;
  }
  let k = 0;
  switch (n & 3) {
    case 3:
      k ^= b[blocks + 2] << 16; // falls through
    case 2:
      k ^= b[blocks + 1] << 8; // falls through
    case 1:
      k ^= b[blocks];
      k = Math.imul(k, 0xcc9e2d51);
      k = (k << 15) | (k >>> 17);
      k = Math.imul(k, 0x1b873593);
      h ^= k;
  }
  h ^= n;
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  return h | 0;
}
// HashingVectorizer(alternate_sign=True): the bucket is |h| mod n, the sign is h's.
export function bucket(token: string) {
  const h = murmur3(token);
  return { index: (h < 0 ? -h : h) & MASK, sign: h < 0 ? -1 : 1 };
}

export function wordGrams(text: string): string[] {
  const tokens = text.match(WORD_TOKEN) || [];
  const out = tokens.slice();
  for (let i = 0; i + 1 < tokens.length; i++) out.push(tokens[i] + ' ' + tokens[i + 1]);
  return out;
}
// scikit-learn's char_wb, n = 3 to 5: each word padded with a space on both sides.
export function charGrams(text: string): string[] {
  const t = pyTrim(text);
  const out: string[] = [];
  if (!t) return out;
  for (const w of t.split(SPLIT)) {
    if (!w) continue;
    const cps = [...(' ' + w + ' ')];
    for (let n = 3; n <= 5; n++) {
      for (let i = 0; i + n <= cps.length; i++) out.push(cps.slice(i, i + n).join(''));
    }
  }
  return out;
}

const ratio = (n: number, d: number) => (d > 0 ? n / d : 0);

// The 17 per-note features, in the model's order (dup_body_bucket is always 0 at inference).
function structural(note: ScorableNote): number[] {
  const content = String((note && note.content) || '');
  const tags = note && Array.isArray(note.tags) ? note.tags : [];
  const lenChars = [...content].length;
  const hosts = new Set<string>();
  let urls = 0;
  for (const m of content.matchAll(URL_HOST)) {
    urls++;
    const host = m[1];
    if (host) hosts.add(host.toLowerCase());
  }
  let p = 0,
    e = 0,
    tt = 0,
    other = 0;
  for (const tag of tags) {
    if (!Array.isArray(tag) || !tag.length) continue;
    if (tag[0] === 'p') p++;
    else if (tag[0] === 'e') e++;
    else if (tag[0] === 't') tt++;
    else other++;
  }
  let emoji = 0,
    letters = 0,
    caps = 0;
  for (const c of content) {
    if (EMOJI.test(c)) emoji++;
    if (LETTER.test(c)) {
      letters++;
      if (UPPER.test(c)) caps++;
    }
  }
  return [
    lenChars,
    count(NONSPACE, content),
    urls,
    hosts.size,
    count(MENTION, content),
    count(HASHTAG, content),
    p,
    e,
    tt,
    other,
    emoji,
    ratio(emoji, lenChars),
    countInvisible(content),
    ratio(caps, letters),
    ratio(count(DIGIT, content), lenChars),
    ratio(count(PUNCT, content), lenChars),
    0
  ];
}

const bodyKey = (text: string) =>
  [...pyTrim(casefold(stripInvisible(String(text || ''))))].slice(0, 200).join('');

// The bundle's 23 dense features: the 17 averaged over its notes, then the six that compare
// them (size, time span, distinct bodies, length spread, shared first word, word overlap).
function bundleFeatures(notes: ScorableNote[]): number[] {
  const rows = notes.map(structural);
  const out = new Array<number>(23).fill(0);
  rows.forEach((r) =>
    r.forEach((v, j) => {
      out[j] += v / notes.length;
    })
  );
  out[17] = notes.length;
  const bodies = new Set(notes.map((n) => bodyKey(n.content || '')).filter(Boolean));
  out[19] = bodies.size;
  if (notes.length >= 2) {
    const times = notes.map((n) => n.created_at || 0).filter(Boolean);
    if (times.length >= 2) out[18] = (Math.max(...times) - Math.min(...times)) / 3600;
    const lens = notes.map((n) => [...String(n.content || '')].length);
    const mean = lens.reduce((a, b) => a + b, 0) / lens.length;
    out[20] = Math.sqrt(lens.reduce((a, v) => a + (v - mean) * (v - mean), 0) / lens.length);
    const sets: Set<string>[] = [];
    const firsts: string[] = [];
    for (const n of notes) {
      const toks = casefold(String(n.content || '')).match(GROUP_TOKEN) || [];
      sets.push(new Set(toks));
      const first = toks[0];
      if (first) firsts.push(first);
    }
    if (firsts.length) {
      const tally = new Map<string, number>();
      let top = 0;
      for (const f of firsts) {
        const c = (tally.get(f) || 0) + 1;
        tally.set(f, c);
        if (c > top) top = c;
      }
      out[21] = top / notes.length;
    }
    let sum = 0,
      pairs = 0;
    for (let i = 0; i < sets.length; i++) {
      for (let j = i + 1; j < sets.length; j++) {
        let inter = 0;
        for (const k of sets[i]) if (sets[j].has(k)) inter++;
        const union = sets[i].size + sets[j].size - inter;
        if (!union) continue;
        sum += inter / union;
        pairs++;
      }
    }
    if (pairs) out[22] = sum / pairs;
  }
  return out;
}

// The bundle as the model sees it: sparse, feature index to value, each value a float32 as
// scikit-learn's matrix holds it.
function features(notes: ScorableNote[]): Map<number, number> {
  const prepared = notes.map((n) => prepare(n.content || ''));
  const x = new Map<number, number>();
  const add = (at: number, token: string) => {
    const { index, sign } = bucket(token);
    const i = at + index;
    x.set(i, (x.get(i) || 0) + sign);
  };
  for (const g of charGrams(prepared.map((p) => p.raw).join(' '))) add(0, g);
  for (const g of wordGrams(prepared.map((p) => p.text).join(' '))) add(WORD_AT, g);
  bundleFeatures(notes).forEach((v, j) => {
    if (v) x.set(STRUCT_AT + j, v);
  });
  for (const [i, v] of x) x.set(i, Math.fround(v));
  return x;
}

export interface NspamModel {
  trees: {
    feature?: Int32Array;
    threshold?: Float64Array;
    left?: Int32Array;
    right?: Int32Array;
    value: Float64Array;
  }[];
  calibX: Float64Array;
  calibY: Float64Array;
}

// static/models/nspam.bin, from an ArrayBuffer.
export function load(buffer: ArrayBuffer): NspamModel {
  const v = new DataView(buffer);
  const magic = String.fromCharCode(v.getUint8(0), v.getUint8(1), v.getUint8(2), v.getUint8(3));
  if (magic !== 'NSPM') throw new Error('not an nspam model');
  if (v.getUint32(4, true) !== 1) throw new Error('unknown nspam model format');
  const nTrees = v.getUint32(8, true);
  const knots = v.getUint32(12, true);
  let at = 16;
  const f64 = (n: number) => {
    const a = new Float64Array(n);
    for (let i = 0; i < n; i++, at += 8) a[i] = v.getFloat64(at, true);
    return a;
  };
  const i32 = (n: number) => {
    const a = new Int32Array(n);
    for (let i = 0; i < n; i++, at += 4) a[i] = v.getInt32(at, true);
    return a;
  };
  const calibX = f64(knots);
  const calibY = f64(knots);
  const trees: NspamModel['trees'] = [];
  for (let t = 0; t < nTrees; t++) {
    const leaves = v.getUint32(at, true);
    at += 4;
    const s = leaves - 1;
    if (s > 0) {
      trees.push({
        feature: i32(s),
        threshold: f64(s),
        left: i32(s),
        right: i32(s),
        value: f64(leaves)
      });
    } else {
      trees.push({ value: f64(leaves) });
    }
  }
  if (at !== buffer.byteLength) throw new Error('nspam model has trailing bytes');
  return { trees, calibX, calibY };
}

// Every split is numeric, default left, no missing values: a feature not present is 0, and
// 0 or less than the threshold goes left. A child below zero is a leaf, ~child.
function margin(model: NspamModel, x: Map<number, number>): number {
  let sum = 0;
  for (const tree of model.trees) {
    const feature = tree.feature;
    const threshold = tree.threshold;
    const left = tree.left;
    const right = tree.right;
    if (!feature || !threshold || !left || !right) {
      sum += tree.value[0];
      continue;
    }
    let node = 0;
    while (node >= 0) {
      const fv = x.get(feature[node]) || 0;
      node = fv <= threshold[node] ? left[node] : right[node];
    }
    sum += tree.value[~node];
  }
  return sum;
}

// np.interp through the isotonic knots, clamped to [0, 1].
function calibrate(model: NspamModel, p: number): number {
  const xs = model.calibX;
  const ys = model.calibY;
  const clamp = (y: number) => Math.min(1, Math.max(0, y));
  if (!xs.length) return clamp(p);
  if (p <= xs[0]) return clamp(ys[0]);
  if (p >= xs[xs.length - 1]) return clamp(ys[ys.length - 1]);
  let i = 0;
  while (xs[i + 1] <= p) i++;
  if (xs[i + 1] === xs[i]) return clamp(ys[i]);
  return clamp(ys[i] + ((p - xs[i]) / (xs[i + 1] - xs[i])) * (ys[i + 1] - ys[i]));
}

